import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:path_provider/path_provider.dart';
import 'package:isar/isar.dart';
import 'Nav/main_scaffold.dart';
import 'core/models/task.dart';
import 'core/models/daily_metric.dart';
import 'core/models/clothing_item.dart';

// Create a global instance of Isar so any screen can access it easily
late Isar isar;

void main() async {
  // 1. Ensure Flutter engine bindings are ready before doing async native disk tasks
  WidgetsFlutterBinding.ensureInitialized();

  // 2. Find a safe, secure folder on your Realme phone to save the database file
  final dir = await getApplicationDocumentsDirectory();

  // 3. Open the database using the schema generated by your build_runner command
  isar = await Isar.open(
    [TaskSchema, DailyMetricSchema, ClothingItemSchema],
    directory: dir.path,
  );

  runApp(const ProviderScope(child: MyApp()));
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'K.A.I.R.O',
      debugShowCheckedModeBanner: false,
      theme: ThemeData.dark(), // Set global dark theme
      home: const MainScaffold(),
    );
  }
}